const searchable = (text) =>
  text
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLocaleLowerCase();
export function searchClubs(query = "", league = "") {
  const q = searchable(query.trim());
  return [...LEGACY_CLUBS, ...CLUB_DATABASE].filter(
    (c) =>
      (!league || c.league === league) &&
      searchable([c.name, ...(c.aliases || [])].join(" ")).includes(q),
  );
}
function rgb(hex) {
  return [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
}
export function colourDistance(a, b) {
  const x = rgb(a),
    y = rgb(b);
  return Math.hypot(...x.map((v, i) => v - y[i]));
}
export function selectKits(home, away) {
  const first = home.home;
  const options = [away.home, away.away].sort(
    (a, b) =>
      colourDistance(first.shirt, b.shirt) -
      colourDistance(first.shirt, a.shirt),
  );
  let second =
    colourDistance(first.shirt, away.home.shirt) >= 130
      ? away.home
      : options[0];
  let emergency = false;
  if (colourDistance(first.shirt, second.shirt) < 130) {
    const light =
      colourDistance(first.shirt, "#ffffff") >
      colourDistance(first.shirt, "#101523");
    second = kit(
      light ? "#ffffff" : "#101523",
      light ? "#101523" : "#ffffff",
      light ? "#ffffff" : "#101523",
      light ? "#ffffff" : "#101523",
    );
    emergency = true;
  }
  return {
    home: first,
    away: second,
    awayAlternate: second !== away.home,
    emergency,
  };
}
